'use strict'

const assert = require('node:assert/strict')
const test = require('node:test')

const {
  ANCHOR,
  applyBatch,
  buildJaRule,
  findInsertionOffset,
  formatBatch,
  formatRule,
  lintTarget,
  parseExactSources,
  validateBatch,
} = require('./conf-rules.js')

const ROUTES = new Set(['/docs/home', '/reference/go/go/v2-Vector-HybridSearch', '/reference/cli/cli/overview'])
const ALLOWLIST = new Map([['/docs/ja-only-page', 'only exists in the ja-JP build']])

const CONF_SAMPLE = `server {
    location = /docs/home { return 301 /docs/index; }
    location = /ja-JP/docs/home { return 301 /ja-JP/docs/index; }

    ${ANCHOR}
    location = /404.html {
        root /usr/share/nginx/html;
    }
}
`

test('parseExactSources reads every exact location source including ja twins', () => {
  const sources = parseExactSources(CONF_SAMPLE)
  assert.deepEqual([...sources].sort(), ['/404.html', '/docs/home', '/ja-JP/docs/home'])
})

test('lintTarget resolves routes, chains, allowlist, and the out-of-scope shapes', () => {
  assert.equal(lintTarget('/docs/home', {routes: ROUTES}).kind, 'route')
  assert.equal(lintTarget('/reference/go/go/v2-Vector-HybridSearch', {routes: ROUTES}).kind, 'route')
  // A chain target is another exact rule in the same conf file.
  assert.equal(lintTarget('/docs/index', {routes: ROUTES, exactSources: new Set(['/docs/index'])}).kind, 'chain')
  assert.equal(lintTarget('/docs/ja-only-page', {routes: ROUTES, allowlist: ALLOWLIST}).kind, 'allowlist')
  // Absolute URLs and $var targets are out of lint scope but resolved.
  assert.equal(lintTarget('https://zilliz.com/pricing', {routes: ROUTES}).kind, 'external')
  assert.equal(lintTarget('/docs/$1', {routes: ROUTES}).kind, 'variable')
})

test('lintTarget judges ja targets against the English routes after the prefix strip', () => {
  assert.equal(lintTarget('/ja-JP/docs/home', {routes: ROUTES}).kind, 'route')
  assert.equal(lintTarget('/ja-JP/docs/retired', {routes: ROUTES}).kind, 'unresolved')
  assert.equal(lintTarget('/ja-JP/', {routes: ROUTES}).kind, 'bare-locale-root')
  assert.equal(lintTarget('/ja-JP/', {routes: ROUTES}).resolved, false)
})

test('lintTarget strips fragments before resolving', () => {
  assert.equal(lintTarget('/docs/home#section', {routes: ROUTES}).kind, 'route')
})

test('buildJaRule swaps the /ja-JP prefix on relative targets and repeats absolute ones', () => {
  assert.deepEqual(buildJaRule('/docs/old', '/docs/home'), {from: '/ja-JP/docs/old', to: '/ja-JP/docs/home'})
  assert.deepEqual(buildJaRule('/pricing', 'https://zilliz.com/pricing'), {from: '/ja-JP/pricing', to: 'https://zilliz.com/pricing'})
  // A ja-prefixed target stays ja-prefixed instead of doubling the locale.
  assert.deepEqual(buildJaRule('/docs/old', '/ja-JP/docs/home'), {from: '/ja-JP/docs/old', to: '/ja-JP/docs/home'})
})

test('formatRule renders the single-line exact block', () => {
  assert.equal(formatRule('/docs/old', '/docs/home'), 'location = /docs/old { return 301 /docs/home; }')
})

test('formatBatch emits the dated header and each en rule followed by its ja twin', () => {
  const batch = formatBatch({
    date: '2026-11-08',
    sourceLabel: 'GA4 window 7d ending 2026-11-08',
    rules: [
      {from: '/reference/go/old', to: '/reference/go/go/new', ja: buildJaRule('/reference/go/old', '/reference/go/go/new')},
      {from: '/pricing', to: 'https://zilliz.com/pricing', ja: buildJaRule('/pricing', 'https://zilliz.com/pricing')},
    ],
  })
  const lines = batch.split('\n')
  assert.equal(lines[0], '    # GA4 404 remediation 2026-11-08 (GA4 window 7d ending 2026-11-08)')
  assert.match(lines[1], /Generated by scripts\/redirects\/ga4-404-remediation\.js/)
  assert.equal(lines[2], '    location = /reference/go/old { return 301 /reference/go/go/new; }')
  assert.equal(lines[3], '    location = /ja-JP/reference/go/old { return 301 /ja-JP/reference/go/go/new; }')
  assert.equal(lines[4], '    location = /pricing { return 301 https://zilliz.com/pricing; }')
  assert.equal(lines[5], '    location = /ja-JP/pricing { return 301 https://zilliz.com/pricing; }')
})

test('validateBatch rejects duplicates, conf collisions, missing twins, and unresolved targets', () => {
  const ja = buildJaRule('/docs/old', '/docs/home')
  const verdict = validateBatch({
    rules: [{from: '/docs/old', to: '/docs/home', ja}],
    confSources: new Set(['/docs/older-rule']),
    routes: ROUTES,
  })
  assert.deepEqual(verdict.errors, [])
  assert.deepEqual(verdict.warnings, [])

  const duplicate = validateBatch({rules: [{from: '/docs/old', to: '/docs/home', ja}], confSources: new Set(['/docs/old']), routes: ROUTES})
  assert.match(duplicate.errors[0], /source already has an exact rule in the conf: \/docs\/old/)

  const twinCollision = validateBatch({
    rules: [
      {from: '/docs/a', to: '/docs/home', ja: {from: '/ja-JP/docs/b', to: '/ja-JP/docs/home'}},
      {from: '/docs/c', to: '/docs/home', ja: {from: '/ja-JP/docs/b', to: '/ja-JP/docs/home'}},
    ],
    confSources: new Set(),
    routes: ROUTES,
  })
  assert.ok(twinCollision.errors.some(error => error.includes('duplicate source inside the batch: /ja-JP/docs/b')))

  const missingTwin = validateBatch({rules: [{from: '/docs/old', to: '/docs/home', ja: null}], confSources: new Set(), routes: ROUTES})
  assert.ok(missingTwin.errors.some(error => error.includes('missing ja twin for /docs/old')))

  const unresolved = validateBatch({rules: [{from: '/docs/old', to: '/docs/retired', ja: buildJaRule('/docs/old', '/docs/retired')}], confSources: new Set(), routes: ROUTES})
  assert.ok(unresolved.errors.some(error => error.includes('unresolved target for /docs/old: /docs/retired (unresolved)')))

  const external = validateBatch({rules: [{from: '/pricing', to: 'https://zilliz.com/pricing', ja: buildJaRule('/pricing', 'https://zilliz.com/pricing')}], confSources: new Set(), routes: ROUTES})
  assert.deepEqual(external.errors, [])
  assert.ok(external.warnings.some(warning => warning.includes('nginx-only target')))
})

test('applyBatch splices the block before the 404 anchor with blank-line separation', () => {
  const batch = formatBatch({date: '2026-11-08', sourceLabel: 'test', rules: [{from: '/docs/old', to: '/docs/home', ja: buildJaRule('/docs/old', '/docs/home')}]})
  const merged = applyBatch(CONF_SAMPLE, batch)
  assert.ok(merged.indexOf('GA4 404 remediation 2026-11-08') < merged.indexOf(ANCHOR))
  // Exactly one blank line separates the batch from the rules above it and
  // the anchor below it.
  assert.match(merged, /\{ return 301 \/ja-JP\/docs\/home; \}\n\n    error_page 404 \/404\.html;/)
  assert.match(merged, /location = \/ja-JP\/docs\/home \{ return 301 \/ja-JP\/docs\/index; \}\n\n    # GA4 404 remediation/)
})

test('findInsertionOffset fails closed when the anchor is missing', () => {
  assert.throws(() => findInsertionOffset('server {\n}\n'), /insertion anchor not found/)
})
