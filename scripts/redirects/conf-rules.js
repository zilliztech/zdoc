'use strict'

// Conf-side rule generation for the GA4 404 remediation tool.
//
// This module is the single writer of redirect content: every mode (direct,
// triage, apply) produces its conf block through formatBatch/applyBatch, and
// every proposal passes validateBatch before anything is emitted. The
// invariants mirror the contracts pinned in deploy/contracts/container.test.mjs:
//   - single-line exact blocks `location = X { return 301 Y; }`
//   - every non-ja source gets a /ja-JP twin (mirror contract)
//   - targets resolve against the sitemap snapshot, another exact source
//     (chain), or the reviewed allowlist; absolute URLs and `$var` targets are
//     allowed but stay nginx-only
//   - no duplicate `location =` sources (nginx rejects them at load time)

const ANCHOR = 'error_page 404 /404.html;'
const ANCHOR_LINE_PATTERN = /^[ \t]*error_page 404 \/404\.html;[ \t]*$/mu
const JA_PREFIX = '/ja-JP'
const EXACT_SOURCE_PATTERN = /location = ([^ {]+) \{/gu
const RETURN_TARGET_PATTERN = /return 301\s+([^;\s]+);/gu

function parseExactSources(confText) {
  return new Set([...confText.matchAll(EXACT_SOURCE_PATTERN)].map(match => match[1]))
}

function isExternalTarget(target) {
  return /^https?:\/\//u.test(target)
}

function isVariableTarget(target) {
  return target.includes('$')
}

function stripJaPrefix(target) {
  if (!target.startsWith(`${JA_PREFIX}/`)) return target
  return target.slice(JA_PREFIX.length)
}

// Mirrors the English target lint in deploy/contracts/container.test.mjs:326.
// Returns one of: route, chain, allowlist, external, variable, bare-locale-root,
// unresolved.
function lintTarget(target, {routes, exactSources = new Set(), allowlist = new Map()}) {
  if (isExternalTarget(target)) return {kind: 'external', resolved: true}
  if (isVariableTarget(target)) return {kind: 'variable', resolved: true}
  let local = target.split('#', 1)[0]
  if (local.startsWith(`${JA_PREFIX}/`)) {
    local = stripJaPrefix(local)
    if (local === '/') return {kind: 'bare-locale-root', resolved: false}
  }
  if (routes.has(local)) return {kind: 'route', resolved: true}
  if (exactSources.has(local)) return {kind: 'chain', resolved: true}
  if (allowlist.has(local)) return {kind: 'allowlist', resolved: true}
  return {kind: 'unresolved', resolved: false}
}

// The ja mirror is mechanical: relative targets swap the /ja-JP prefix on both
// sides, absolute targets keep the same destination on both twins (the ja
// locale falls back to English content, see the nginx-only hop comment in the
// 2026-10-31 conf batch).
function buildJaRule(from, to) {
  if (isExternalTarget(to) || isVariableTarget(to)) {
    return {from: `${JA_PREFIX}${from}`, to}
  }
  return {from: `${JA_PREFIX}${from}`, to: `${JA_PREFIX}${stripJaPrefix(to)}`}
}

function formatRule(from, to) {
  return `location = ${from} { return 301 ${to}; }`
}

// Renders the batch exactly like the hand-appended ones: a dated provenance
// comment, then every en rule followed by its ja twin, 4-space indented to sit
// inside the server block.
function formatBatch({date, sourceLabel, rules}) {
  const lines = [
    `    # GA4 404 remediation ${date} (${sourceLabel})`,
    `    # Generated by scripts/redirects/ga4-404-remediation.js; reviewed before merging.`,
  ]
  for (const rule of rules) {
    lines.push(`    ${formatRule(rule.from, rule.to)}`)
    if (rule.ja) lines.push(`    ${formatRule(rule.ja.from, rule.ja.to)}`)
  }
  return `${lines.join('\n')}\n`
}

function findInsertionOffset(confText) {
  // Match the whole indented anchor line so `before` keeps trailing rule lines
  // and `after` keeps the anchor's own indentation.
  const match = confText.match(ANCHOR_LINE_PATTERN)
  if (!match) throw new Error(`insertion anchor not found: ${ANCHOR}`)
  return match.index
}

// Validates one proposed batch before emission. errors block the write;
// warnings surface in the proposal but do not.
function validateBatch({rules, confSources, routes, allowlist = new Map()}) {
  const errors = []
  const warnings = []
  const seen = new Set()
  for (const rule of rules) {
    for (const source of [rule.from, rule.ja ? rule.ja.from : null]) {
      if (!source) continue
      if (seen.has(source)) errors.push(`duplicate source inside the batch: ${source}`)
      seen.add(source)
      if (confSources.has(source)) errors.push(`source already has an exact rule in the conf: ${source}`)
    }
    if (!rule.ja) errors.push(`missing ja twin for ${rule.from}`)
    for (const target of [rule.to, rule.ja ? rule.ja.to : null]) {
      if (!target) continue
      const verdict = lintTarget(target, {routes, exactSources: confSources, allowlist})
      if (!verdict.resolved) errors.push(`unresolved target for ${rule.from}: ${target} (${verdict.kind})`)
      if (verdict.kind === 'external' || verdict.kind === 'variable') {
        warnings.push(`nginx-only target (absent from the SPA map) for ${rule.from}: ${target}`)
      }
    }
  }
  return {errors, warnings}
}

// Appends the batch right before the 404 anchor, keeping one blank line of
// separation on each side of the new block.
function applyBatch(confText, batchText) {
  const offset = findInsertionOffset(confText)
  const before = confText.slice(0, offset)
  const after = confText.slice(offset)
  const trimmedBefore = `${before.replace(/[ \t]*\n+$/u, '')}\n`
  return `${trimmedBefore}\n${batchText}\n${after}`
}

module.exports = {
  ANCHOR,
  applyBatch,
  buildJaRule,
  findInsertionOffset,
  formatBatch,
  formatRule,
  isExternalTarget,
  isVariableTarget,
  lintTarget,
  parseExactSources,
  stripJaPrefix,
  validateBatch,
}
